export type Key = keyof typeof dict;

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string; date: (iso: string | null | undefined) => string }
const I18n = createContext<Ctx>(null as unknown as Ctx);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("sms_lang") as Lang) || "en");
  const setLang = (l: Lang) => { localStorage.setItem("sms_lang", l); setLangState(l); };
  return (
    <I18n.Provider value={{ lang, setLang, t: (k) => dict[k][lang], date: (iso) => formatDate(iso, lang) }}>
      {children}
    </I18n.Provider>
  );
}
export const useI18n = () => useContext(I18n);
